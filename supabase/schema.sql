-- Tabelas do app Financeiro.
-- Como usar: no painel do Supabase, abra SQL Editor > New query, cole este arquivo inteiro e clique em Run.
-- Pode rodar mais de uma vez: não apaga nada que já exista.

-- Lançamentos: o extrato de cada conta (receitas, despesas e transferências já realizadas)
create table if not exists public.fin_lancamentos (
  id bigint generated by default as identity primary key,
  conta text not null,
  data date not null,
  tipo text not null check (tipo in ('receita', 'despesa', 'transferencia')),
  pessoa text not null default '',
  plano text not null default '',         -- plano de contas, no formato "Grupo:Subgrupo"
  centro text not null default '',        -- centro de custo
  historico text not null default '',
  valor numeric(14,2) not null,           -- positivo = entrada, negativo = saída
  competencia date,
  criado_em timestamptz not null default now()
);
create index if not exists fin_lancamentos_data_idx on public.fin_lancamentos (data);
create index if not exists fin_lancamentos_conta_idx on public.fin_lancamentos (conta);

-- Programações: contas a pagar e a receber em aberto
create table if not exists public.fin_programacoes (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('pagar', 'receber')),
  conta text not null default '',
  parcela text not null default '',
  pessoa text not null default '',
  plano text not null default '',
  centro text not null default '',
  historico text not null default '',
  vencimento date,
  frequencia text not null default '',
  valor numeric(14,2) not null default 0, -- valor da próxima parcela
  total numeric(14,2) not null default 0,
  restantes integer check (restantes is null or restantes >= 0), -- parcelas que faltam; vazio = recorrente sem fim
  criado_em timestamptz not null default now()
);
alter table public.fin_programacoes add column if not exists restantes integer check (restantes is null or restantes >= 0);
create index if not exists fin_programacoes_vencimento_idx on public.fin_programacoes (vencimento);

-- Pessoas: clientes e fornecedores
create table if not exists public.fin_pessoas (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('cliente', 'fornecedor')),
  nome text not null,
  razao text not null default '',
  pessoa text not null default 'PF' check (pessoa in ('PF', 'PJ')),
  documento text not null default '',
  email text not null default '',
  telefone text not null default '',
  cidade text not null default '',
  uf text not null default '',
  inativo boolean not null default false,
  criado_em timestamptz not null default now()
);

-- Listas: contas, planos de contas e centros de custo cadastrados à mão.
-- ativo = false esconde o item das sugestões sem apagar o histórico.
create table if not exists public.fin_listas (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('conta', 'plano', 'centro')),
  nome text not null,
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  unique (tipo, nome)
);

-- Segurança: RLS ligado e nenhuma política.
-- Assim a chave pública (anon) não lê nem grava nada; só o servidor do app, com a chave service_role, acessa.
alter table public.fin_lancamentos enable row level security;
alter table public.fin_programacoes enable row level security;
alter table public.fin_pessoas enable row level security;
alter table public.fin_listas enable row level security;
